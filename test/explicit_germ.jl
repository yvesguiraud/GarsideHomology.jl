# A germ given by its table of simple products, for the tests of the germ interface (a
# tool of the tests, not part of the package). Lengths, divisions, descents, lcms,
# smallest words and the canonical numbering are deduced by brute force, independently
# of the generic methods of GarsideHomology, which is enough for a few hundred simples.
#
# Examples: the classical and dual braid monoids of the dihedral group I₂(m), realised in
# the group itself as interval germs.

using GarsideHomology

"""
    ExplicitGerm(keys, atom_keys, identity_key, products)

The germ whose simples are the elements `keys` (any objects: group elements, names),
with the identity `identity_key`, the atoms `atom_keys` in their order, and the simple
products `products`, a dictionary `(x, y) => xy` holding the pairs whose product is
simple (the products by the identity may be omitted). The simples are numbered in the
canonical order (0 for the identity, then by length and smallest word), the keys being
kept for the tests (`G.keys[s + 1]` is the key of the simple `s`) but ignored by `==`.
"""
struct ExplicitGerm{K} <: GarsideHomology.AbstractGerm
    natoms::Int
    words::Vector{Vector{Int32}}              # words[s + 1]: smallest word of s
    products::Dict{NTuple{2, Int32}, Int32}   # (s, t) => st, when st is simple
    quotients::Dict{NTuple{2, Int32}, Int32}  # (s, t) => s \ t, when s ≼ t
    descents::Vector{GarsideHomology.StaticBitSet{K}}   # descents[s + 1]
    lcms::Matrix{NTuple{2, Int32}}            # lcms[ω + 1, a] = (ω ∨ a, ω \ (ω ∨ a))
    keys::Vector{Any}                         # keys[s + 1]
end

function ExplicitGerm(keys::AbstractVector, atom_keys::AbstractVector, identity_key,
                      products::AbstractDict)
    n = length(keys)
    index = Dict{Any, Int}(k => i for (i, k) in enumerate(keys))
    length(index) == n || throw(ArgumentError("repeated keys"))
    e = index[identity_key]
    A = [index[a] for a in atom_keys]
    N = length(A)
    # Provisional table of products, P[i, j] = k or 0.
    P = zeros(Int, n, n)
    for ((x, y), z) in products
        P[index[x], index[y]] = index[z]
    end
    for i in 1:n
        P[e, i] = i
        P[i, e] = i
    end
    # Lengths, from the identity by right multiplication by the atoms.
    len = fill(-1, n)
    len[e] = 0
    queue = [e]
    while !isempty(queue)
        x = popfirst!(queue)
        for a in A
            y = P[x, a]
            if y != 0 && len[y] < 0
                len[y] = len[x] + 1
                push!(queue, y)
            end
        end
    end
    all(>=(0), len) || throw(ArgumentError("simples not generated by the atoms"))
    for i in 1:n, j in 1:n
        k = P[i, j]
        k == 0 || len[k] == len[i] + len[j] ||
            throw(ArgumentError("length not additive on $(keys[i]) · $(keys[j])"))
    end
    # Left divisibility and left quotients: Q[i, k] = j with P[i, j] = k, or 0.
    Q = zeros(Int, n, n)
    for i in 1:n, j in 1:n
        k = P[i, j]
        k == 0 && continue
        Q[i, k] == 0 || Q[i, k] == j ||
            throw(ArgumentError("two quotients of $(keys[k]) by $(keys[i])"))
        Q[i, k] = j
    end
    divides(i, k) = Q[i, k] != 0
    # Smallest words, by increasing length.
    words = Vector{Vector{Int32}}(undef, n)
    for x in sortperm(len)
        if x == e
            words[x] = Int32[]
        else
            α = findfirst(a -> divides(a, x), A)
            α === nothing && throw(ArgumentError("$(keys[x]) has no left descent"))
            words[x] = vcat(Int32(α), words[Q[A[α], x]])
        end
    end
    # Canonical numbering: identity, then by length and word.
    order = sortperm(1:n; by = i -> (len[i], words[i]))
    id = zeros(Int32, n)                       # id[i]: number of the provisional simple i
    for (r, i) in enumerate(order)
        id[i] = r - 1
    end
    id[e] == 0 && all(id[A[α]] == α for α in 1:N) ||
        throw(ArgumentError("the canonical numbering does not start with e and the atoms"))
    K = max(1, cld(N, 64))
    prods = Dict{NTuple{2, Int32}, Int32}()
    quots = Dict{NTuple{2, Int32}, Int32}()
    for i in 1:n, j in 1:n
        P[i, j] == 0 || (prods[(id[i], id[j])] = id[P[i, j]])
        Q[i, j] == 0 || (quots[(id[i], id[j])] = id[Q[i, j]])
    end
    desc = Vector{GarsideHomology.StaticBitSet{K}}(undef, n)
    lcms = Matrix{NTuple{2, Int32}}(undef, n, N)
    for x in 1:n
        desc[id[x] + 1] = GarsideHomology.StaticBitSet{K}(α for α in 1:N if divides(A[α], x))
        for α in 1:N
            common = [m for m in 1:n if divides(x, m) && divides(A[α], m)]
            least = filter(m -> all(divides(m, z) for z in common), common)
            length(least) == 1 ||
                throw(ArgumentError("$(keys[x]) and atom $α: $(length(least)) least common multiples"))
            m = only(least)
            lcms[id[x] + 1, α] = (id[m], id[Q[x, m]])
        end
    end
    sorted_keys = Vector{Any}(undef, n)
    for i in 1:n
        sorted_keys[id[i] + 1] = keys[i]
    end
    return ExplicitGerm{K}(N, [words[i] for i in order], prods, quots, desc, lcms, sorted_keys)
end

GarsideHomology.natoms(G::ExplicitGerm) = G.natoms
GarsideHomology.nsimples(G::ExplicitGerm) = length(G.words)
GarsideHomology.simples(G::ExplicitGerm) = Int32(0):Int32(length(G.words) - 1)
Base.length(G::ExplicitGerm, s::Integer) = length(G.words[s + 1])
GarsideHomology.product(G::ExplicitGerm, s::Integer, t::Integer) = get(G.products, (Int32(s), Int32(t)), nothing)
GarsideHomology.ldiv(G::ExplicitGerm, s::Integer, t::Integer) = get(G.quotients, (Int32(s), Int32(t)), nothing)
GarsideHomology.left_descents(G::ExplicitGerm, s::Integer) = G.descents[s + 1]

function GarsideHomology.lcm_atom(G::ExplicitGerm, ω::Integer, a::Integer)
    1 <= a <= G.natoms || throw(ArgumentError("$a is not an atom"))
    m, τ = G.lcms[ω + 1, a]
    return (lcm = m, complement = τ)
end

function GarsideHomology.opposite(G::ExplicitGerm)
    k(s) = G.keys[s + 1]
    reversed = Dict{Tuple{Any, Any}, Any}((k(t), k(s)) => k(u) for ((s, t), u) in G.products)
    return ExplicitGerm(G.keys, G.keys[2:(G.natoms + 1)], G.keys[1], reversed)
end

Base.:(==)(G::ExplicitGerm, H::ExplicitGerm) =
    G.natoms == H.natoms && G.words == H.words && G.products == H.products &&
    G.quotients == H.quotients && G.descents == H.descents && G.lcms == H.lcms
Base.hash(G::ExplicitGerm, h::UInt) = hash(G.words, hash(G.natoms, hash(:ExplicitGerm, h)))

Base.show(io::IO, G::ExplicitGerm) =
    print(io, "ExplicitGerm with ", G.natoms, " atoms and ", length(G.words), " simples")

# ------------------------------------------------------------------------------------
# Interval germs of the dihedral group I₂(m)

# Elements of the dihedral group of order 2m: (k, 0) is the rotation ρᵏ, (k, 1) the
# reflection σₖ = ρᵏσ₀; σ₀ρ = ρ⁻¹σ₀.
dihedral_mul(m, x, y) = x[2] == 0 ? (mod(x[1] + y[1], m), y[2]) : (mod(x[1] - y[1], m), 1 - y[2])
dihedral_elements(m) = [(k, ε) for ε in 0:1 for k in 0:(m - 1)]

# The interval germ of the simples `S` of a group with product `mul` and length `len`:
# x·y is simple when xy is in S and len(xy) = len(x) + len(y).
function interval_germ(S, atoms, identity, mul, len)
    inS = Set(S)
    products = Dict{Tuple{Any, Any}, Any}()
    for x in S, y in S
        z = mul(x, y)
        z in inS && len(z) == len(x) + len(y) && (products[(x, y)] = z)
    end
    return ExplicitGerm(collect(S), atoms, identity, products)
end

"""
    classical_dihedral_germ(m)

The germ of the classical braid monoid B⁺(I₂(m)): atoms s = σ₀ and t = σ₁, simples the
2m elements of the group, Coxeter length; m = 3 gives B⁺(A₂).
"""
function classical_dihedral_germ(m::Integer)
    mul(x, y) = dihedral_mul(m, x, y)
    s, t, e = (0, 1), (1, 1), (0, 0)
    # Coxeter length: distance to the identity in the Cayley graph of s and t.
    len = Dict{Any, Int}(e => 0)
    queue = Any[e]
    while !isempty(queue)
        x = popfirst!(queue)
        for g in (s, t)
            y = mul(x, g)
            haskey(len, y) || (len[y] = len[x] + 1; push!(queue, y))
        end
    end
    return interval_germ(dihedral_elements(m), [s, t], e, mul, x -> len[x])
end

"""
    dual_dihedral_germ(m)

The germ of the dual braid monoid B*(I₂(m)): atoms the m reflections r₁, …, rₘ with
rᵢ = σᵢ₋₁, so that r₁r₂ = r₂r₃ = ⋯ = rₘr₁ = Δ = ρ⁻¹; simples the identity, the atoms and
Δ, reflection length; m = 3 gives B*(A₂).
"""
function dual_dihedral_germ(m::Integer)
    mul(x, y) = dihedral_mul(m, x, y)
    e, c = (0, 0), (mod(-1, m), 0)
    reflections = [(k, 1) for k in 0:(m - 1)]
    len(x) = x == e ? 0 : x[2] == 1 ? 1 : 2
    return interval_germ(vcat([e], reflections, [c]), reflections, e, mul, len)
end

"""
    check_germ(G)

Check by brute force, over all simples (a tabulated germ), the consistency of the
interface of `G`: identity, atoms and canonical numbering; product, division and
divisibility; descents; lcms with the atoms, minimal among the common multiples; words
and lexicographic comparison; Δ; the opposite germ. Returns the number of failures, each
reported by a warning, so that a single `@test check_germ(G) == 0` covers it.
"""
function check_germ(G)
    failures = 0
    fail(msg) = (failures += 1; @warn msg; nothing)
    S = GarsideHomology.simples(G)
    n, N = nsimples(G), natoms(G)
    S == 0:(n - 1) || fail("simples(G) = $S")
    one(G) === Int32(0) && isone(G, 0) && !isone(G, 1) || fail("identity")
    GarsideHomology.atoms(G) == 1:N || fail("atoms(G)")
    divides(s, t) = GarsideHomology.ldiv(G, s, t) !== nothing
    for a in 1:N
        length(G, a) == 1 && GarsideHomology.word(G, a) == [a] || fail("atom $a")
    end
    for s in S, t in S
        p = GarsideHomology.product(G, s, t)
        if p !== nothing
            p isa Int32 && GarsideHomology.ldiv(G, s, p) == t && length(G, p) == length(G, s) + length(G, t) ||
                fail("product($s, $t) = $p")
        end
        q = GarsideHomology.ldiv(G, s, t)
        q === nothing || (q isa Int32 && GarsideHomology.product(G, s, q) == t) || fail("ldiv($s, $t) = $q")
        GarsideHomology.is_left_divisor(G, s, t) == (q !== nothing) || fail("is_left_divisor($s, $t)")
        GarsideHomology.isless_lex(G, s, t) == isless(GarsideHomology.word(G, s), GarsideHomology.word(G, t)) ||
            fail("isless_lex($s, $t)")
        GarsideHomology.isless_deglex(G, s, t) ==
            isless((length(G, s), GarsideHomology.word(G, s)), (length(G, t), GarsideHomology.word(G, t))) ||
            fail("isless_deglex($s, $t)")
    end
    for s in S
        GarsideHomology.product(G, 0, s) == s && GarsideHomology.product(G, s, 0) == s && GarsideHomology.ldiv(G, 0, s) == s &&
            GarsideHomology.ldiv(G, s, s) == 0 || fail("identity and $s")
        D = GarsideHomology.left_descents(G, s)
        collect(D) == [a for a in 1:N if divides(a, s)] || fail("left_descents($s) = $D")
        w = GarsideHomology.word(G, s)
        length(w) == length(G, s) || fail("word($s) = $w")
        foldl((x, a) -> GarsideHomology.product(G, x, a)::Int32, w; init = Int32(0)) == s ||
            fail("word($s) = $w does not give $s")
        isempty(w) || first(w) == first(D) || fail("word($s) does not start with the smallest descent")
        s == 0 || (length(G, s - 1), GarsideHomology.word(G, s - 1)) < (length(G, s), w) ||
            fail("canonical order at $s")
        divides(s, n - 1) || fail("$s does not divide Δ = $(n - 1)")
        for a in 1:N
            r = GarsideHomology.lcm_atom(G, s, a)
            m, τ = r
            r isa NamedTuple{(:lcm, :complement), NTuple{2, Int32}} || fail("type of lcm_atom($s, $a)")
            GarsideHomology.product(G, s, τ) == m && divides(a, m) || fail("lcm_atom($s, $a) = $r")
            all(divides(m, x) for x in S if divides(s, x) && divides(a, x)) ||
                fail("lcm_atom($s, $a) = $r not least")
            divides(a, s) && !(m == s && τ == 0) && fail("lcm_atom($s, $a) = $r with a ≼ s")
        end
    end
    # Opposite: an involution, with the reversed products. The simple s = a₁⋯aₖ of G is
    # aₖ ·ᵒᵖ ⋯ ·ᵒᵖ a₁ in the opposite germ.
    O = GarsideHomology.opposite(G)
    natoms(O) == N && nsimples(O) == n || fail("size of the opposite")
    GarsideHomology.opposite(O) == G || fail("opposite(opposite(G)) != G")
    image = [foldl((x, a) -> GarsideHomology.product(O, x, a)::Int32, reverse(GarsideHomology.word(G, s));
                   init = Int32(0)) for s in S]
    sort(image) == S || fail("the simples of the opposite are not those of G")
    for s in S, t in S
        p = GarsideHomology.product(G, s, t)
        q = GarsideHomology.product(O, image[t + 1], image[s + 1])
        (p === nothing ? q === nothing : q == image[p + 1]) || fail("opposite on ($s, $t)")
    end
    return failures
end

